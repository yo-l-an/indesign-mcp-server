#!/usr/bin/env python3
"""Build lib/font-atlas.js: anti-aliased glyphs of Inter for the review images.

Dev-only. The server itself has no dependency: it reads the generated atlas.

    python3 -m venv /tmp/fontenv && /tmp/fontenv/bin/pip install pillow
    /tmp/fontenv/bin/python scripts/build-font-atlas.py [path/to/Inter-SemiBold.otf]

Inter (https://rsms.me/inter/) by Rasmus Andersson is licensed under the SIL Open Font
License 1.1; the rendered glyph bitmaps are distributed under the same license.
"""
import base64, json, os, sys, zlib
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else '/Library/Fonts/Inter-SemiBold.otf'
SIZES = [10, 11, 13, 16, 20]
CHARS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0xC0, 0x100)]
    + list('–—…«»·→←↑↓×’‘“”€°')
)
OUT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'font-atlas.js')

sizes = {}
for size in SIZES:
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    glyphs, data = {}, bytearray()
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = font.getlength(ch)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            px = img.tobytes()
        else:
            px = b''
        glyphs[ch] = [len(data), w, h, x0, y0, round(adv, 2)]
        data += px
    sizes[size] = {'ascent': ascent, 'descent': descent, 'glyphs': glyphs,
                   'data': base64.b64encode(zlib.compress(bytes(data), 9)).decode('ascii')}

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/build-font-atlas.py - do not edit.\n')
    f.write('// Glyphs of Inter SemiBold (https://rsms.me/inter/) by Rasmus Andersson, SIL Open Font\n')
    f.write('// License 1.1 (https://openfontlicense.org). Each glyph: [offset, width, height, x, y, advance];\n')
    f.write('// data = zlib-deflated 8-bit coverage, base64.\n')
    f.write('export const FONT_ATLAS = ' + json.dumps(sizes, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes')
